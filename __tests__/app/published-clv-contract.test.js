const fs = require('fs')
const path = require('path')

const captureSrc = fs.readFileSync(path.join(__dirname, '../../scripts/capture-published-closes.js'), 'utf8')
const reportSrc = fs.readFileSync(path.join(__dirname, '../../scripts/report-published-clv.js'), 'utf8')
const closingSrc = fs.readFileSync(path.join(__dirname, '../../lib/closing-line.js'), 'utf8')
const sql = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/007_published_close_odds.sql'), 'utf8')
const rollback = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/007_published_close_odds_rollback.sql'), 'utf8')
const docs = fs.readFileSync(path.join(__dirname, '../../docs/migrations/007_published_close_odds.md'), 'utf8')
const sql008 = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/008_closing_odds_close_capture_uniq.sql'), 'utf8')
const rollback008 = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/008_closing_odds_close_capture_uniq_rollback.sql'), 'utf8')
const docs008 = fs.readFileSync(path.join(__dirname, '../../docs/migrations/008_closing_odds_close_capture_uniq.md'), 'utf8')
const ops = fs.readFileSync(path.join(__dirname, '../../operations/README.md'), 'utf8')
const pkg = fs.readFileSync(path.join(__dirname, '../../package.json'), 'utf8')
const schema = fs.readFileSync(path.join(__dirname, '../../prisma/schema.prisma'), 'utf8')

describe('S1 closing-price capture contract', () => {
  test('does not re-run morning fetch-live-odds or add Prisma close scalars', () => {
    expect(captureSrc).not.toMatch(/from ['"].*fetch-live-odds/)
    expect(captureSrc).toMatch(/Never re-runs morning fetch-live-odds/)
    expect(captureSrc).toMatch(/createScriptSupabaseClient/)
    expect(captureSrc).toMatch(/isOpsWriteQuietPeriod/)
    expect(captureSrc).toMatch(/one Odds API event-odds call per oddsApiEventId/)
    expect(captureSrc).toMatch(/SUPABASE_REQUIRE_SECRET_KEY/)
    expect(captureSrc).toMatch(/classifyCloseCaptureGames/)
    expect(captureSrc).toMatch(/applyPublishedCloseUpdate/)
    expect(closingSrc).toMatch(/isPreStartStatus/)
    expect(closingSrc).toMatch(/\.is\('closeOdds', null\)/)
    expect(closingSrc).toMatch(/CLOSE_CAPTURE_WINDOW_MINUTES = 35/)
    expect(closingSrc).toMatch(/CLOSE_CAPTURE_MIN_LEAD_MINUTES = 1/)
    expect(closingSrc).toMatch(/CLOSE_CAPTURE_NEAR_START_MINUTES = 10/)
    expect(reportSrc).toMatch(/Never writes/)
    expect(reportSrc).toMatch(/Never calls The Odds API/)
    expect(schema).not.toMatch(/closeOdds/)
    expect(sql).toMatch(/ADD COLUMN IF NOT EXISTS "closeOdds"/)
    expect(sql).toMatch(/SET lock_timeout/)
    expect(sql).toMatch(/DO NOT run from CI/)
    expect(rollback).toMatch(/DROP COLUMN IF EXISTS "closeOdds"/)
    expect(rollback).toMatch(/SET lock_timeout/)
  })

  test('008 close-capture unique index is additive, reports mixed groups, and only deletes exact dupes', () => {
    expect(sql008).toMatch(/ClosingOdds_close_capture_uniq/)
    expect(sql008).toMatch(/id LIKE 'clvclose:%'/)
    expect(sql008).toMatch(/Never deletes a non-duplicate/)
    expect(sql008).toMatch(/NOT undone by the rollback/)
    expect(docs008).toMatch(/not\*\* undone by the rollback file/)
    expect(sql008).toMatch(/exact_count = ranked.grp_count/)
    expect(sql008).toMatch(/CREATE UNIQUE INDEX IF NOT EXISTS/)
    expect(sql008).toMatch(/Skipping unique index/)
    expect(sql008).toMatch(/SET lock_timeout/)
    expect(sql008).toMatch(/DO NOT run from CI/)
    expect(rollback008).toMatch(/DROP INDEX IF EXISTS "ClosingOdds_close_capture_uniq"/)
    expect(docs008).toMatch(/Paste `scripts\/migrations\/008_closing_odds_close_capture_uniq.sql`/)
    expect(closingSrc).toMatch(/CLOSING_ODDS_CLOSE_CAPTURE_UNIQ/)
    expect(schema).toMatch(/partial unique index/)
  })

  test('owner commands and quota notes are documented', () => {
    expect(pkg).toMatch(/"capture:published-closes": "node scripts\/capture-published-closes\.js"/)
    expect(pkg).toMatch(/"capture:published-closes:apply": "node scripts\/capture-published-closes\.js --apply"/)
    expect(pkg).toMatch(/"report:published-clv": "node scripts\/report-published-clv\.js"/)
    expect(pkg).toMatch(/"report:shadow-nhl": "node scripts\/report-shadow-nhl\.js"/)
    expect(ops).toMatch(/capture-published-closes\.js --dry-run/)
    expect(ops).toMatch(/capture:published-closes:apply/)
    expect(ops).toMatch(/\$env:CLV_APPLY=1/)
    expect(ops).toMatch(/leftover/)
    expect(ops).toMatch(/CLV_APPLY=1/)
    expect(ops).toMatch(/record-mlb-window-props\.js/)
    expect(ops).toMatch(/record-mlb-window-props\.js --postseason/)
    expect(ops).toMatch(/35 minutes/)
    expect(ops).toMatch(/:16 and :46 ET/)
    expect(ops).toMatch(/CLOSE_CAPTURE_STATUS=ok\|partial\|failed/)
    expect(ops).toMatch(/ODDS_CLOSE_CAPTURE_DAILY_CAP/)
    expect(ops).toMatch(/T−10/)
    expect(ops).toMatch(/0,4,16,26,36,46,56 8-22 \* \* \*/)
    expect(ops).toMatch(/Empty window is a 0-credit/)
    expect(ops).toMatch(/onConflict: id/)
    expect(ops).toMatch(/:15–:17/)
    expect(ops).toMatch(/:06–:14/)
    expect(ops).toMatch(/:56 \/ :00/)
    expect(ops).toMatch(/:04:30/)
    expect(ops).toMatch(/early pass/)
    expect(captureSrc).toMatch(/CLOSE_CAPTURE_RECOMMENDED_CRON/)
    expect(captureSrc).toMatch(/shouldSkipLiveCloseOverwrite/)
    expect(closingSrc).toMatch(/CLOSE_CAPTURE_RECOMMENDED_CRON = '0,4,16,26,36,46,56 8-22 \* \* \*'/)
    expect(ops).not.toMatch(/npm run capture:published-closes -- --apply/)
    expect(captureSrc).toMatch(/MODE: APPLY/)
    expect(captureSrc).toMatch(/CLV_APPLY/)
    expect(docs).toMatch(/markets × regions/)
    expect(docs).toMatch(/HTTP calls \/ day/)
    expect(docs).toMatch(/35 minutes/)
    expect(docs).toMatch(/London NFL/)
    expect(docs).toMatch(/Downtime/)
    expect(closingSrc).toMatch(/summarizePublishedClv/)
  })
})
