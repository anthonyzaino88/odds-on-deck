const fs = require('fs')
const path = require('path')

const snapshotSrc = fs.readFileSync(path.join(__dirname, '../../scripts/snapshot-published-odds.js'), 'utf8')
const snapshotLib = fs.readFileSync(path.join(__dirname, '../../lib/odds-snapshot.js'), 'utf8')
const captureSrc = fs.readFileSync(path.join(__dirname, '../../scripts/capture-published-closes.js'), 'utf8')
const fetchSrc = fs.readFileSync(path.join(__dirname, '../../scripts/fetch-live-odds.js'), 'utf8')
const freshSrc = fs.readFileSync(path.join(__dirname, '../../scripts/fetch-fresh-games.js'), 'utf8')
const reportSrc = fs.readFileSync(path.join(__dirname, '../../scripts/report-published-clv.js'), 'utf8')
const closingSrc = fs.readFileSync(path.join(__dirname, '../../lib/closing-line.js'), 'utf8')
const sql = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/011_odds_snapshots.sql'), 'utf8')
const rollback = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/011_odds_snapshots_rollback.sql'), 'utf8')
const docs = fs.readFileSync(path.join(__dirname, '../../docs/migrations/011_odds_snapshots.md'), 'utf8')
const ops = fs.readFileSync(path.join(__dirname, '../../operations/README.md'), 'utf8')
const pkg = fs.readFileSync(path.join(__dirname, '../../package.json'), 'utf8')
const schema = fs.readFileSync(path.join(__dirname, '../../prisma/schema.prisma'), 'utf8')

describe('Published odds snapshot contract', () => {
  test('011 is additive, manual, and verified on information_schema', () => {
    expect(sql).toMatch(/CREATE TABLE IF NOT EXISTS "OddsSnapshot"/)
    expect(sql).toMatch(/SET lock_timeout = '5s'/)
    expect(sql).toMatch(/DO NOT run from CI/)
    expect(sql).toMatch(/information_schema.columns/)
    expect(sql).toMatch(/"propValidationId"/)
    expect(sql).toMatch(/"capturedAt" TIMESTAMPTZ/)
    expect(sql).toMatch(/OddsSnapshot_propValidationId_capturedAt_idx/)
    expect(sql).toMatch(/midday/)
    expect(rollback).toMatch(/DROP TABLE IF EXISTS "OddsSnapshot"/)
    expect(rollback).toMatch(/SET lock_timeout = '5s'/)
    expect(docs).toMatch(/Paste `scripts\/migrations\/011_odds_snapshots\.sql`/)
    expect(docs).toMatch(/information_schema.columns/)
    expect(schema).not.toMatch(/OddsSnapshot/)
  })

  test('script is Published-only, dry-run default, and budget-gated', () => {
    expect(snapshotSrc).toMatch(/Never snapshots shadow-published/)
    expect(snapshotSrc).toMatch(/purpose: 'snapshot'/)
    expect(snapshotSrc).toMatch(/createOddsApiBudget/)
    expect(snapshotSrc).toMatch(/isOpsWriteQuietPeriod/)
    expect(snapshotSrc).toMatch(/shouldSkipPaidCloseCaptureFetch/)
    expect(snapshotSrc).toMatch(/regions: SNAPSHOT_REGIONS/)
    expect(snapshotSrc).toMatch(/SNAPSHOT_STATUS/)
    expect(snapshotSrc).toMatch(/SNAPSHOT_EVENTS/)
    expect(snapshotSrc).toMatch(/CALLS_USED/)
    expect(snapshotSrc).toMatch(/formatSnapshotCredits/)
    expect(snapshotLib).toMatch(/CREDITS=/)
    expect(snapshotSrc).toMatch(/isMissingOddsSnapshotError/)
    expect(snapshotSrc).not.toMatch(/from ['"].*fetch-live-odds/)
    expect(snapshotSrc).not.toMatch(/--nfl-all/)
    expect(snapshotSrc).not.toMatch(/CLV_APPLY/)
    expect(snapshotSrc).not.toMatch(/apply-stale/)
    expect(snapshotLib).toMatch(/isPublishedCohort/)
    expect(snapshotLib).toMatch(/isShadowPublishedCohort/)
    expect(snapshotLib).toMatch(/Never writes source='close'/)
    expect(snapshotLib).toMatch(/DEFAULT_SNAPSHOT_DAILY_PASSES = 2/)
    expect(snapshotLib).toMatch(/DEFAULT_SNAPSHOT_MAX_EVENT_CALLS = 8/)
    expect(snapshotLib).toMatch(/DEFAULT_SNAPSHOT_FRESH_MINUTES = 90/)
    expect(pkg).toMatch(/"snapshot:published-odds": "node scripts\/snapshot-published-odds\.js"/)
    expect(pkg).toMatch(/"snapshot:published-odds:apply": "node scripts\/snapshot-published-odds\.js --apply"/)
    expect(ops).toMatch(/snapshot:published-odds:apply/)
    expect(ops).toMatch(/ODDS_SNAPSHOT_DAILY_PASSES/)
  })

  test('does not change morning fetch, close capture, or CLV math', () => {
    expect(fetchSrc).not.toMatch(/from ['"].*snapshot-published-odds/)
    expect(freshSrc).toMatch(/let applyStale = false/)
    expect(freshSrc).toMatch(/--apply-stale/)
    expect(captureSrc).toMatch(/--nfl-all/)
    expect(captureSrc).toMatch(/purpose: 'close-capture'/)
    expect(captureSrc).toMatch(/Never re-runs morning fetch-live-odds/)
    expect(closingSrc).toMatch(/clvProb = implied\(close\) − implied\(recorded\)/)
    expect(reportSrc).toMatch(/Never writes/)
    expect(reportSrc).toMatch(/Never calls The Odds API/)
    expect(snapshotSrc).toMatch(/does not change CLV/)
    expect(snapshotLib).toMatch(/snapshots never rewrite odds/)
  })
})
