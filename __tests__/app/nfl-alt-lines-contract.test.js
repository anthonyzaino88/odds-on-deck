const fs = require('fs')
const path = require('path')

const altSrc = fs.readFileSync(path.join(__dirname, '../../scripts/fetch-published-nfl-alt-lines.js'), 'utf8')
const altLib = fs.readFileSync(path.join(__dirname, '../../lib/nfl-alt-lines.js'), 'utf8')
const snapshotSrc = fs.readFileSync(path.join(__dirname, '../../scripts/snapshot-published-odds.js'), 'utf8')
const captureSrc = fs.readFileSync(path.join(__dirname, '../../scripts/capture-published-closes.js'), 'utf8')
const fetchSrc = fs.readFileSync(path.join(__dirname, '../../scripts/fetch-live-odds.js'), 'utf8')
const freshSrc = fs.readFileSync(path.join(__dirname, '../../scripts/fetch-fresh-games.js'), 'utf8')
const reportSrc = fs.readFileSync(path.join(__dirname, '../../scripts/report-published-clv.js'), 'utf8')
const closingSrc = fs.readFileSync(path.join(__dirname, '../../lib/closing-line.js'), 'utf8')
const apiSrc = fs.readFileSync(path.join(__dirname, '../../app/api/props/route.js'), 'utf8')
const uiSrc = fs.readFileSync(path.join(__dirname, '../../components/PlayerPropsFilter.js'), 'utf8')
const sql = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/012_nfl_alt_quotes.sql'), 'utf8')
const rollback = fs.readFileSync(path.join(__dirname, '../../scripts/migrations/012_nfl_alt_quotes_rollback.sql'), 'utf8')
const docs = fs.readFileSync(path.join(__dirname, '../../docs/migrations/012_nfl_alt_quotes.md'), 'utf8')
const ops = fs.readFileSync(path.join(__dirname, '../../operations/README.md'), 'utf8')
const pkg = fs.readFileSync(path.join(__dirname, '../../package.json'), 'utf8')
const schema = fs.readFileSync(path.join(__dirname, '../../prisma/schema.prisma'), 'utf8')

describe('Published NFL alt-line contract', () => {
  test('012 is additive, manual, and verified on information_schema', () => {
    expect(sql).toMatch(/ADD COLUMN IF NOT EXISTS "altQuotes"/)
    expect(sql).toMatch(/ADD COLUMN IF NOT EXISTS "altQuoteUpdatedAt"/)
    expect(sql).toMatch(/SET lock_timeout = '5s'/)
    expect(sql).toMatch(/DO NOT run from CI/)
    expect(sql).toMatch(/information_schema.columns/)
    expect(sql).toMatch(/ENABLE ROW LEVEL SECURITY/)
    expect(sql).toMatch(/GRANT ALL ON TABLE "PlayerPropCache" TO service_role/)
    expect(sql).not.toMatch(/REVOKE ALL ON TABLE "PlayerPropCache"/)
    expect(sql).toMatch(/relrowsecurity/)
    expect(rollback).toMatch(/DROP COLUMN IF EXISTS "altQuotes"/)
    expect(rollback).toMatch(/DROP COLUMN IF EXISTS "altQuoteUpdatedAt"/)
    expect(rollback).toMatch(/SET lock_timeout = '5s'/)
    expect(docs).toMatch(/Paste `scripts\/migrations\/012_nfl_alt_quotes\.sql`/)
    expect(docs).toMatch(/information_schema.columns/)
    expect(docs).toMatch(/relrowsecurity/)
    expect(schema).not.toMatch(/altQuotes/)
    expect(schema).not.toMatch(/altQuoteUpdatedAt/)
  })

  test('script is Published-NFL-only, dry-run default, and budget-gated', () => {
    expect(altSrc).toMatch(/Never fetches shadow-published/)
    expect(altSrc).toMatch(/purpose: 'nfl-alt'/)
    expect(altSrc).toMatch(/createOddsApiBudget/)
    expect(altSrc).toMatch(/isOpsWriteQuietPeriod/)
    expect(altSrc).toMatch(/shouldSkipPaidCloseCaptureFetch/)
    expect(altSrc).toMatch(/shouldRefuseSnapshotStart/)
    expect(altSrc).toMatch(/Quiet window before write/)
    expect(altSrc).toMatch(/aborting after setup, before fetch/)
    expect(altSrc).toMatch(/regions: NFL_ALT_REGIONS/)
    expect(altSrc).toMatch(/NFL_ALT_STATUS/)
    expect(altSrc).toMatch(/NFL_ALT_EVENTS/)
    expect(altSrc).toMatch(/CALLS_USED/)
    expect(altSrc).toMatch(/formatNflAltCredits/)
    expect(altLib).toMatch(/DEFAULT_NFL_ALT_DAILY_CREDITS = 48/)
    expect(altLib).toMatch(/NFL_ALT_REGIONS = Object.freeze\(\['us'\]\)/)
    expect(altLib).toMatch(/player_pass_yds_alternate/)
    expect(altLib).toMatch(/player_rush_yds_alternate/)
    expect(altLib).toMatch(/player_reception_yds_alternate/)
    expect(altLib).not.toMatch(/player_shots_on_goal_alternate/)
    expect(altSrc).not.toMatch(/from ['"].*fetch-live-odds/)
    expect(altSrc).not.toMatch(/--nfl-all/)
    expect(altSrc).not.toMatch(/CLV_APPLY/)
    expect(altSrc).not.toMatch(/SNAPSHOT_APPLY/)
    expect(altSrc).not.toMatch(/apply-stale/)
    expect(pkg).toMatch(/"fetch:nfl-alt-lines": "node scripts\/fetch-published-nfl-alt-lines\.js"/)
    expect(pkg).toMatch(/"fetch:nfl-alt-lines:apply": "node scripts\/fetch-published-nfl-alt-lines\.js --apply"/)
    expect(ops).toMatch(/ODDS_NFL_ALT_DAILY_CREDITS/)
    expect(ops).toMatch(/fetch:nfl-alt-lines:apply/)
  })

  test('does not change morning fetch, close capture, snapshots, or CLV math', () => {
    expect(fetchSrc).not.toMatch(/from ['"].*fetch-published-nfl-alt-lines/)
    expect(fetchSrc).not.toMatch(/player_pass_yds_alternate/)
    expect(freshSrc).toMatch(/let applyStale = false/)
    expect(freshSrc).toMatch(/--apply-stale/)
    expect(captureSrc).toMatch(/--nfl-all/)
    expect(captureSrc).toMatch(/purpose: 'close-capture'/)
    expect(captureSrc).not.toMatch(/from ['"].*fetch-published-nfl-alt-lines/)
    expect(snapshotSrc).not.toMatch(/from ['"].*fetch-published-nfl-alt-lines/)
    expect(snapshotSrc).toMatch(/purpose: 'snapshot'/)
    expect(closingSrc).toMatch(/clvProb = implied\(close\) − implied\(recorded\)/)
    expect(reportSrc).toMatch(/Never writes/)
    expect(reportSrc).toMatch(/Never calls The Odds API/)
    expect(altSrc).toMatch(/does not change CLV/)
    expect(altLib).toMatch(/CLV stays entry/)
  })

  test('API and UI keep copy honest and never expose shadow alt lines', () => {
    expect(apiSrc).toMatch(/attachPublicAltLines/)
    expect(apiSrc).toMatch(/isShadowPublishedCohort/)
    expect(uiSrc).toMatch(/US books · last shop · not the close/)
    expect(uiSrc).not.toMatch(/real-time/i)
    expect(uiSrc).not.toMatch(/10\+ books/)
    expect(altLib).toMatch(/isNflAltEligibleCacheProp/)
    expect(altLib).toMatch(/isShadowPublishedCohort/)
  })
})
